/**
 * Структура правовых документов.
 *
 * Документы лежат данными, а не разметкой: их читают и правят как текст,
 * изменения видны в diff построчно, а версия и дата редакции — обязательная
 * часть каждого документа (на версию согласия ссылается запись о его получении,
 * см. #866).
 */

/** Абзац или список внутри пункта. */
export type Block = string | { list: string[] };

export interface Clause {
  /** Номер и заголовок пункта, например «3. Цели обработки». */
  title: string;
  blocks: Block[];
}

export interface LegalDocument {
  /** Заголовок документа целиком. */
  title: string;
  /**
   * Версия документа. Меняется при любой правке смысла: по ней видно, какую
   * редакцию принял пользователь.
   */
  version: string;
  /** Дата редакции в человеческом виде. */
  revisionDate: string;
  /** Вводная строка под заголовком (необязательно). */
  lead?: string;
  clauses: Clause[];
}

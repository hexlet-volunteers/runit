/**
 * Незаполненные реквизиты, без которых документы недействительны.
 *
 * Список намеренно короткий — только то, что требует закон. ИНН, ОГРН и номер
 * в реестре сюда не входят: их отсутствие не делает документ недействительным,
 * и держать из-за них предупреждение на глазах у посетителей незачем.
 */
export const missingOperatorFields = (): string[] => {
  const required: Array<[keyof Operator, string]> = [
    ['legalAddress', 'адрес оператора'],
    ['dataProtectionEmail', 'адрес для обращений по вопросам ПДн'],
  ];

  return required
    .filter(([field]) => OPERATOR[field] === null)
    .map(([, label]) => label);
};

/**
 * Значение реквизита для вставки в текст. Пустое поле выводится заметным
 * маркером, а не пропускается молча: незаполненный адрес оператора должно быть
 * видно сразу.
 */
export const field = (value: string | null): string =>
  value ?? '[НЕ ЗАПОЛНЕНО]';

/**
 * Строка с ИНН и ОГРН — или пустая, если они не заданы. Нужна, чтобы в тексте
 * не появлялось «ИНН [НЕ ЗАПОЛНЕНО]» для необязательных реквизитов.
 */
export const registrationDetails = (): string => {
  const parts: string[] = [];
  if (OPERATOR.inn) parts.push(`ИНН ${OPERATOR.inn}`);
  if (OPERATOR.ogrn) parts.push(`ОГРН ${OPERATOR.ogrn}`);
  return parts.join(', ');
};

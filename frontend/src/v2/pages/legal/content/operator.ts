/**
 * Реквизиты оператора персональных данных — в одном месте (#867).
 *
 * Так они не расходятся между Политикой, Согласием и Пользовательским
 * соглашением: закон требует указывать оператора в каждом из документов
 * (152-ФЗ, ст. 9 ч. 4 п. 3, ст. 18 ч. 3), и три копии реквизитов рано или
 * поздно разъехались бы.
 *
 * ИНН, ОГРН и адрес взяты из открытых источников (ЕГРЮЛ). Перед публикацией их
 * стоит сверить с актуальной выпиской: адрес юридического лица меняется, а
 * неверный адрес оператора в согласии делает согласие недействительным
 * (ст. 9 ч. 4 п. 3).
 */

export interface Operator {
  /** Полное наименование оператора. */
  name: string;
  /**
   * Адрес оператора. Обязателен: без него согласие не соответствует
   * части 4 статьи 9.
   */
  legalAddress: string | null;
  /**
   * Адрес для обращений по вопросам обработки персональных данных.
   * Обязателен: иначе субъект не может реализовать свои права (ст. 14).
   */
  dataProtectionEmail: string | null;
  /** Общий адрес поддержки. */
  supportEmail: string;
  /** ИНН — не требуется законом, но принято указывать для идентификации. */
  inn: string | null;
  /** ОГРН — то же. */
  ogrn: string | null;
  /**
   * Номер записи в реестре операторов Роскомнадзора. Появляется после подачи
   * уведомления (152-ФЗ, ст. 22). Пока его нет, соответствующая строка в
   * Политике не выводится — публиковать несуществующий номер нельзя.
   */
  notificationRegistryNumber: string | null;
}


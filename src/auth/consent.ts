/**
 * Версии согласия на обработку персональных данных (#866).
 *
 * Согласие обязано быть конкретным и информированным (152-ФЗ, ст. 9 ч. 1), а
 * значит нужно знать, какую именно редакцию документа видел пользователь.
 * Поэтому вместе с регистрацией фиксируются версия и дата согласия — без этого
 * доказать правомерность обработки нечем.
 *
 * Текст документа живёт на фронтенде
 * (frontend/src/v2/pages/legal/content/consent.ts), здесь — только перечень
 * версий, которые сервер готов принять. Дублирование намеренное: сервер не
 * должен доверять клиенту произвольную строку, иначе в записях о согласии
 * окажется мусор. При изменении документа версия поднимается в двух местах —
 * это же и заставляет заметить, что изменение требует нового согласия.
 */

/** Текущая редакция документа. Должна совпадать с CONSENT_VERSION на фронтенде. */
export const CURRENT_CONSENT_VERSION = '1.0';

/**
 * Версии, которые сервер принимает при регистрации. Прошлые редакции остаются
 * в списке: между деплоем и перезагрузкой открытой вкладки клиент присылает
 * ещё старую версию, и отклонять регистрацию из-за этого нельзя.
 */
const ACCEPTED_CONSENT_VERSIONS = new Set([CURRENT_CONSENT_VERSION]);

export const isAcceptedConsentVersion = (version: string): boolean =>
  ACCEPTED_CONSENT_VERSIONS.has(version);
